#!/usr/bin/env python
"""Generate a combinatorial matrix of SFINCS input decks for parity sweeps.

Upstream's example suite is a *sample* of the input space, not a cover of it,
and the gaps are where parity bugs survive: 57 of the 59 golden decks in
``tests/ref`` pin ``Nxi_for_x_option = 0``, so the default ramp -- the one a
deck gets when it says nothing -- went years without ever being compared
against Fortran.  It was wrong.  This tool exists so that class of gap is
closed by construction rather than by noticing.

The axes swept are the switches that select genuinely different code paths:
geometry scheme, collision operator, radial electric field, ``Phi1``,
``RHSMode``, the ``Nxi_for_x`` ramp, species count, and resolution.  Only the
analytic geometries (schemes 1-4) are emitted by default, so the matrix needs
no equilibrium files and runs anywhere.

Combinations are filtered against ``validateInput.F90`` rather than tried and
discarded: SFINCS silently *rewrites* several of them (``RHSMode=3`` forces
``Nxi_for_x_option=0``, ``Nx=1`` and drops ``Phi1``), so an unfiltered sweep
would quietly compare decks that are not the decks it thinks it is.

Decks are written as ``<out>/<name>/input.namelist``, the layout
:mod:`parity_performance_matrix` consumes::

    python tools/benchmarks/generate_deck_matrix.py --out /tmp/decks
    python tools/benchmarks/parity_performance_matrix.py \
        --examples /tmp/decks --fortran-binary /path/to/sfincs --out m.jsonl
"""

from __future__ import annotations

import argparse
import itertools
import json
from dataclasses import dataclass
from pathlib import Path

#: Collision operators both codes implement.  ``collisionOperator = 3`` (the
#: improved Sugama model) is a dkx research extension with no Fortran
#: counterpart, so it is excluded from parity matrices by default.
PARITY_COLLISION_OPERATORS = (0, 1)

RESOLUTIONS = {
    "tiny": dict(n_theta=5, n_zeta=5, n_xi=6, n_x=3),
    "small": dict(n_theta=9, n_zeta=11, n_xi=12, n_x=4),
    "medium": dict(n_theta=13, n_zeta=15, n_xi=24, n_x=5),
}


@dataclass(frozen=True)
class Case:
    """One point of the input matrix."""

    geometry: int
    collision: int
    er: float
    phi1: bool
    rhs_mode: int
    nxi_ramp: int
    species: int
    resolution: str

    @property
    def name(self) -> str:
        return (
            f"geo{self.geometry}_col{self.collision}"
            f"_{'Er' if self.er else 'noEr'}"
            f"_{'phi1' if self.phi1 else 'nophi1'}"
            f"_rhs{self.rhs_mode}_ramp{self.nxi_ramp}"
            f"_{self.species}sp_{self.resolution}"
        )


def is_valid(case: Case) -> str | None:
    """Reason the case is rejected, or ``None`` when SFINCS accepts it as written.

    Encodes ``validateInput.F90``.  The point is to reject rather than let
    SFINCS *rewrite*: it silently forces several settings and then solves a
    different problem than the deck describes, which would make a parity
    comparison meaningless while still looking like it ran.
    """
    if case.rhs_mode == 2:
        if case.species != 1:
            return "RHSMode=2 is single-species only"
        if case.phi1:
            return "RHSMode=2 is incompatible with Phi1"
    if case.rhs_mode == 3:
        if case.phi1:
            return "RHSMode=3 silently drops Phi1"
        if case.nxi_ramp != 0:
            return "RHSMode=3 silently forces Nxi_for_x_option=0"
        if case.species != 1:
            return "monoenergetic coefficients are single-species"
    if case.phi1 and case.species < 2:
        return "Phi1 needs at least two species for quasineutrality"
    if case.phi1 and case.collision != 0:
        return "Phi1 in dkx is admitted against Fokker-Planck collisions"
    return None


_TEMPLATE = """\
! Generated by tools/benchmarks/generate_deck_matrix.py -- do not edit by hand.
&general
  RHSMode = {rhs_mode}
/
&geometryParameters
  geometryScheme = {geometry}
/
&speciesParameters
  Zs = {zs}
  mHats = {m_hats}
  nHats = {n_hats}
  THats = {t_hats}
  dNHatdrHats = {dn}
  dTHatdrHats = {dt}
/
&physicsParameters
  Delta = 4.5694d-3
  alpha = 1d+0
  nu_n = 8.3156d-3
  Er = {er}
  collisionOperator = {collision}
  includePhi1 = {phi1}
  includeXDotTerm = .false.
  includeElectricFieldTermInXiDot = .false.
/
&resolutionParameters
  Ntheta = {n_theta}
  Nzeta = {n_zeta}
  Nxi = {n_xi}
  Nx = {n_x}
  solverTolerance = 1d-11
/
&otherNumericalParameters
  Nxi_for_x_option = {nxi_ramp}
/
&preconditionerOptions
/
&export_f
/
"""


def render(case: Case) -> str:
    """The namelist text for one case."""
    if case.species == 1:
        species = dict(zs="1", m_hats="1", n_hats="1.0d+0", t_hats="1.0d+0",
                       dn="-0.5", dt="-2.0")
    else:
        # Hydrogen plus electrons, quasineutral as written so Phi1 runs clean.
        species = dict(zs="1 -1", m_hats="1 5.446d-4", n_hats="1.0d+0 1.0d+0",
                       t_hats="1.0d+0 1.0d+0", dn="-0.5 -0.5", dt="-2.0 -2.0")
    return _TEMPLATE.format(
        rhs_mode=case.rhs_mode,
        geometry=case.geometry,
        er=f"{case.er}d+0",
        collision=case.collision,
        phi1=".true." if case.phi1 else ".false.",
        nxi_ramp=case.nxi_ramp,
        **species,
        **RESOLUTIONS[case.resolution],
    )


def enumerate_cases(
    *,
    geometries: tuple[int, ...],
    collisions: tuple[int, ...],
    resolutions: tuple[str, ...],
) -> tuple[list[Case], list[tuple[Case, str]]]:
    """All axis combinations, split into accepted and rejected-with-reason."""
    accepted: list[Case] = []
    rejected: list[tuple[Case, str]] = []
    axes = itertools.product(
        geometries, collisions, (0.0, -1.5), (False, True), (1, 2, 3),
        (0, 1, 2), (1, 2), resolutions,
    )
    for geometry, collision, er, phi1, rhs_mode, ramp, species, resolution in axes:
        case = Case(geometry, collision, er, phi1, rhs_mode, ramp, species, resolution)
        reason = is_valid(case)
        (rejected.append((case, reason)) if reason else accepted.append(case))
    return accepted, rejected


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--geometries", type=int, nargs="+", default=[1, 2, 3, 4])
    parser.add_argument(
        "--collisions", type=int, nargs="+", default=list(PARITY_COLLISION_OPERATORS)
    )
    parser.add_argument("--resolutions", nargs="+", default=["tiny", "small"])
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    accepted, rejected = enumerate_cases(
        geometries=tuple(args.geometries),
        collisions=tuple(args.collisions),
        resolutions=tuple(args.resolutions),
    )
    print(f"{len(accepted)} valid, {len(rejected)} rejected of "
          f"{len(accepted) + len(rejected)} combinations")
    if args.dry_run:
        for case, reason in rejected[:10]:
            print(f"  reject {case.name}: {reason}")
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    for case in accepted:
        directory = args.out / case.name
        directory.mkdir(exist_ok=True)
        (directory / "input.namelist").write_text(render(case))
    (args.out / "manifest.json").write_text(
        json.dumps(
            {
                "n_cases": len(accepted),
                "cases": [
                    {**vars(case), "name": case.name} for case in accepted
                ],
                "rejected": [
                    {"name": case.name, "reason": reason} for case, reason in rejected
                ],
            },
            indent=2,
        )
        + "\n"
    )
    print(f"wrote {len(accepted)} decks to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
